const fs = require("node:fs");
const path = require("node:path");
const peggy = require("peggy");
const directory = path.resolve(__dirname, "../packages/core/src/parser/platform/peggy");
fs.mkdirSync(path.join(directory, "generated"), { recursive: true });
for (const name of ["surge", "loon", "qx"]) {
  const filename = path.join(directory, `${name}.pegjs`);
  const source = peggy.generate(fs.readFileSync(filename, "utf8"), { output: "source", format: "es" });
  fs.writeFileSync(path.join(directory, "generated", `${name}.js`), `// Generated by npm run generate:parsers. Do not edit.\n${source}\n`);
  fs.writeFileSync(path.join(directory, `${name}.js`), `import * as parser from "./generated/${name}.js";\n\nexport default function getParser() {\n  return parser;\n}\n`);
}
